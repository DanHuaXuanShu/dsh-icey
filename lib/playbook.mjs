/**
 * 给模型看的完整规则卡（markdown）。
 * 不塞进工具描述（太长、每一步都花 token），改成需要时取。
 */
export function playbookText() {
  const p = PLAYBOOK
  const lines = []
  lines.push(`# ${p.game} 规则卡（${p.genre}）`)
  lines.push('')
  lines.push('> 每条都来自本机实测，不是文档抄来的。')
  lines.push('')
  lines.push('## Game Rules')
  for (const r of p.rules) lines.push(`- ${r}`)
  lines.push('')
  lines.push('## Common Keys')
  for (const [k, d] of p.keys) lines.push(`- \`${k}\` —— ${d}`)
  lines.push('')
  lines.push('## 招式表（内部动作名来自游戏程序集）')
  for (const [name, key, note] of p.moves) lines.push(`- **${name}**　\`${key}\`　${note}`)
  lines.push('')
  lines.push(`## 招式强化树（游戏内界面逐项抄录，${p.skillTree.length} 项）`)
  lines.push('')
  lines.push('| 技能 | 等级 | 输入 | 类型 | 说明 |')
  lines.push('|---|---|---|---|---|')
  for (const [name, lv, input, note, kind] of p.skillTree) lines.push(`| ${name} | ${lv} | \`${input}\` | ${kind || ''} | ${note} |`)
  lines.push('')
  lines.push(`> ⚠️ ${p.upgradeMenuWarning}`)
  lines.push('')
  if (p.advancedTech) {
    lines.push('## 进阶技巧（取消衔接，来自实战教学视频）')
    for (const s of p.advancedTech) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.actionEffects) {
    lines.push('## 动作效果（做什么 / 副作用）')
    for (const [name, what, note] of p.actionEffects) lines.push(`- \`${name}\` ${what} —— ${note}`)
    lines.push('')
  }
  if (p.namingSystem) {
    lines.push('## 招式名的命名体系（名字=功能位）')
    for (const s of p.namingSystem) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.menuRule) {
    lines.push('## 停在菜单里怎么办')
    for (const s of p.menuRule) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.executeRule) {
    lines.push('## 处决（收益最高的动作）')
    for (const s of p.executeRule) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.guideArrow) {
    lines.push('## 跟随画面箭头')
    for (const s of p.guideArrow) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.combatNotes) {
    lines.push('## 战斗（从 24 分钟实战数据里学的）')
    for (const s of p.combatNotes) lines.push(`- ${s}`)
    lines.push('')
  }
  if (p.exploration) {
    lines.push('## 探索 / 找宝箱（有依据才动手）')
    for (const s of p.exploration) lines.push(`- ${s}`)
    lines.push('')
  }
  lines.push('## 怎么判断「真的在前进」')
  for (const s of p.progressSignals) lines.push(`- ${s}`)
  lines.push('')
  lines.push('## 危险动作（会真的搞坏东西）')
  for (const h of p.hazards) {
    lines.push(`### ${h.what}`)
    lines.push(`- 怎么做：${h.how}`)
    lines.push(`- 风险：${h.danger}`)
  }
  lines.push('')
  if (p.combatDetection) {
    lines.push('## 插件的「战斗判断」怎么读')
    for (const s of p.combatDetection) lines.push(`- ${s}`)
    lines.push('')
  }
  lines.push('## 分工')
  lines.push('- 插件负责**反射**：抓帧、按键、发现「没进展」、判定走不通并掉头。')
  lines.push('- 模型负责**策略**：看截图判断这扇门要不要等剧情、该往哪走、要不要读旁白。')
  if (p.hands) {
    lines.push('')
    lines.push('## 谁的手在键盘上（平时你按，战斗插件为主）')
    for (const s of p.hands) lines.push(`- ${s}`)
  }
  return lines.join('\n')
}
