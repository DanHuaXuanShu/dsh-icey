/**
 * lib/games/icey/layout.mjs —— ICEY 的画面布局与亮度阈值
 * ============================================================================
 * 这是「世界层」里最靠界面的一小块：**只放数字**，不放逻辑。
 * 逻辑在 lib/ui/scan.mjs（通用原语），两者合起来才是 ICEY 的画面指标。
 *
 * 为什么单独拿出来：
 *   换一个游戏时，要改的就是这个文件（HUD 在哪、提示框在哪、多亮算亮），
 *   而 scan.mjs 一个字都不用动。
 *
 * 所有值都是 2026-10 在 ICEY（1606×935 窗口、按比例缩放到 480/640 分析）
 * 上实测出来的，注释里写了依据 —— 别再当凭空数字改。
 * ============================================================================
 */

/** 左上一带的 HUD（血条 / 连击数 / 能量刻度） */
export const HUD_BOX = { x0: 0.03, y0: 0.08, x1: 0.32, y1: 0.20 }
/**
 * 血条是亮青色、数字是亮黄，都远高于 150；
 * 标题界面的夜空/雪地在这一带是暗的 ⇒ 150 能把「进没进游戏」分开。
 */
export const HUD_LUM_MIN = 150
/** HUD 区域采样步长（不用逐像素，2 行 / 4 列已经够稳） */
export const HUD_Y_STEP = 2
export const HUD_X_STEP = 4

/**
 * 「互动提示框」：角色右边、屏幕中下部那一条。
 * 能互动的东西靠近时会浮出白字提示（「⏎: 开启强化」那种），
 * 不能互动的（锁住的门、纯装饰）没有提示框 —— 这是分辨它们的关键信号。
 */
export const PROMPT_BOX = { x0: 0.55, y0: 0.50, x1: 0.90, y1: 0.75 }
/** 提示文字是很纯的白（240+），比场景里最亮的地面还亮 */
export const PROMPT_LUM_MIN = 235

/** 旁白/字幕：屏幕下方中间那条（ICEY 的旁白就压在这里） */
export const SUBTITLE_BOX = { x0: 0.12, y0: 0.70, x1: 0.88, y1: 0.95 }
export const SUBTITLE_LUM_MIN = 225
/** 判定「有字幕」的阈值：这块区域白字占比超过它就算有旁白在念 */
export const SUBTITLE_MIN = 0.02

/**
 * 特效强度：全画面「很亮」像素占比，阈值 210。
 * 实测（24 分钟战斗数据）：大伤害（掉血>5%）前 1.5 秒 vfx 6.61%，全局平均 4.09%
 * ⇒ 亮闪明显升高 ≈ 敌人要放大招，这是**可检测的预警信号**。
 */
export const VFX_LUM_MIN = 210
export const VFX_DANGER = 0.055

/** 菜单判定：左侧出现 ≥9 行文字条带、或者整体压暗超过 90% */
export const MENU_LIST_BANDS = 9
export const MENU_DARK_RATIO = 0.90
