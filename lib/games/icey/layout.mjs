/** 旁白/字幕：屏幕下方中间那条（ICEY 的旁白就压在这里） */
export const SUBTITLE_BOX = { x0: 0.12, y0: 0.70, x1: 0.88, y1: 0.95 }
export const SUBTITLE_LUM_MIN = 225
/** 判定「有字幕」的阈值：这块区域白字占比超过它就算有旁白在念 */
