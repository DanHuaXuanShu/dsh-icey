/**
 * 连击数字和它下面那条进度条是金黄色（#FFD700 一带）。
 * 血条是青色、钱是青白色、字幕是纯白 —— 都不会命中这里。
 */
export function isComboYellow(r, g, b) {
  return r > 170 && g > 120 && b < 110 && r - b > 90 && g - b > 50
}

