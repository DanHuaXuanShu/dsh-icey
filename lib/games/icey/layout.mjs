/**
 * 「互动提示框」：角色右边、屏幕中下部那一条。
 * 能互动的东西靠近时会浮出白字提示（「⏎: 开启强化」那种），
 * 不能互动的（锁住的门、纯装饰）没有提示框 —— 这是分辨它们的关键信号。
 */
export const PROMPT_BOX = { x0: 0.55, y0: 0.50, x1: 0.90, y1: 0.75 }
/** 提示文字是很纯的白（240+），比场景里最亮的地面还亮 */
